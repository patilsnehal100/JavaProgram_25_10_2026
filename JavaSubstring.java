
public class JavaSubstring {
	
	
	    public static void main(String[] args) {
	        
	       
	        String str="My name is Snehal Suhas Patil";
	        
	        String str1=str.substring(9); //it start from index 9 
	        String str2=str.substring(1,13); // it start from index 1 and print char before index 13 
	        System.out.println(str1);
	        System.out.println(str2);
	    }
	

}
